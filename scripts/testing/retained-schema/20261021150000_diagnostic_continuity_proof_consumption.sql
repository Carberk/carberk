-- The issuance binding predicate, unchanged, now shared by issuance, consumption
-- and the consuming report INSERT. Before B's report exists it also proves A has
-- no successor and B has no first report.
CREATE FUNCTION diagnostic_continuity_proof_bound(proof diagnostic_continuity_proofs) RETURNS boolean LANGUAGE sql STABLE AS $$
 SELECT EXISTS (SELECT 1 FROM diagnostic_reports a JOIN inspection_orders ao ON ao.id=a."orderId"
   JOIN inspection_orders b ON b.id=proof."candidateOrderId"
   WHERE a.id=proof."predecessorReportId" AND ao.id=proof."predecessorOrderId" AND ao.id<>b.id
    AND a."erasedAt" IS NULL AND ao."erasedAt" IS NULL AND b."erasedAt" IS NULL AND ao.synthetic AND b.synthetic
    AND a.status IN ('finalized','withdrawn') AND b.status='arrived'
    AND ao."physicalAuthorization" IS NOT NULL AND b."physicalAuthorization" IS NOT NULL
    AND a.audience='buyer_private' AND ao.audience='buyer_private' AND b.audience='buyer_private'
    AND ao."commissionerId" IS NOT NULL AND ao."commissionerId"=b."commissionerId"
    AND a.version=(proof.content->'predecessor'->>'reportVersion')::int
    AND a."snapshotHash"=proof.content->'predecessor'->>'snapshotHash'
    AND a."identityRecordId"=proof.content->'predecessor'->>'identityRecordId'
    AND a."identityRecordHash"=proof.content->'predecessor'->>'identityRecordHash'
    AND b.version=(proof.content->'candidate'->>'orderVersion')::int
    AND NOT EXISTS (SELECT 1 FROM diagnostic_reports s WHERE s."predecessorId"=a.id OR s."orderId"=b.id))
$$;

-- Insert and invalidation rules are unchanged. Consumption is one transition of an
-- unused, uninvalidated, unerased proof whose bindings, both order epochs and
-- evidence generations still hold. Consumed proofs are never invalidated.
CREATE OR REPLACE FUNCTION diagnostic_continuity_proof_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF OLD."consumedReportId" IS NULL AND NEW."consumedReportId" IS NOT NULL THEN
   IF (to_jsonb(NEW)-'consumedReportId'-'consumedAt') IS DISTINCT FROM (to_jsonb(OLD)-'consumedReportId'-'consumedAt')
    OR OLD."invalidatedAt" IS NOT NULL OR OLD."erasedAt" IS NOT NULL OR NEW."consumedAt" IS NULL OR NEW."rightsUntil"<=NEW."consumedAt"
    OR NOT diagnostic_continuity_proof_bound(NEW)
    OR NOT EXISTS (SELECT 1 FROM inspection_orders ao JOIN inspection_orders b ON b.id=NEW."candidateOrderId"
     WHERE ao.id=NEW."predecessorOrderId" AND ao.version=(NEW.bindings->'predecessor'->>'version')::int
      AND ao.epoch=NEW.bindings->'predecessor'->>'epoch' AND ao."identityEvidenceGeneration"=(NEW.bindings->'predecessor'->>'evidenceGeneration')::int
      AND b.epoch=NEW.bindings->'candidate'->>'epoch' AND b."identityEvidenceGeneration"=(NEW.bindings->'candidate'->>'evidenceGeneration')::int)
   THEN RAISE EXCEPTION 'diagnostic_continuity_proof_consumption'; END IF;
   RETURN NEW;
  END IF;
  IF (to_jsonb(NEW)-'invalidatedAt') IS DISTINCT FROM (to_jsonb(OLD)-'invalidatedAt')
   OR (OLD."invalidatedAt" IS NOT NULL AND NEW."invalidatedAt" IS DISTINCT FROM OLD."invalidatedAt")
   OR NEW."invalidatedAt" IS NULL THEN RAISE EXCEPTION 'diagnostic_continuity_proof_immutable'; END IF;
  RETURN NEW;
 END IF;
 IF NEW."erasedAt" IS NOT NULL OR NEW."invalidatedAt" IS NOT NULL OR NEW."consumedReportId" IS NOT NULL OR NEW.content IS NULL OR NEW.bindings IS NULL
  OR NEW.content->>'proofId' IS DISTINCT FROM NEW.id OR NEW.content->>'policyVersion'<>'ADR-0108'
  OR NEW.content->>'method'<>'comparative_attestation' OR NEW.content->>'result'<>'same_vehicle'
  OR NEW.content->>'issuedBy' IS DISTINCT FROM NEW."issuerId"
  OR NEW.content->>'linkingTechnicianId' IS DISTINCT FROM NEW."linkingTechnicianId"
  OR NEW."issuerId"=NEW."linkingTechnicianId" OR NEW."rightsUntil"<=NEW."issuedAt"
  OR NOT diagnostic_continuity_proof_bound(NEW)
 THEN RAISE EXCEPTION 'diagnostic_continuity_proof_binding'; END IF;
 RETURN NEW;
END $$;

-- Unchanged except that a consumed proof keeps its consumption: later source
-- changes, including B's own report INSERT, invalidate only unused proofs.
CREATE OR REPLACE FUNCTION diagnostic_continuity_source_changed() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r JSONB; prior JSONB; oid TEXT; uid TEXT; sid TEXT;
BEGIN
 IF TG_OP='DELETE' THEN r=to_jsonb(OLD); ELSE r=to_jsonb(NEW); END IF;
 IF TG_OP='UPDATE' AND to_jsonb(OLD) IS NOT DISTINCT FROM r THEN RETURN NULL; END IF;
 IF TG_TABLE_NAME='inspection_orders' THEN oid=r->>'id';
 ELSIF TG_TABLE_NAME IN ('diagnostic_reports','diagnostic_identity_records','diagnostic_identity_evidence','diagnostic_identity_provenance','diagnostic_order_assignments') THEN oid=r->>'orderId';
 ELSIF TG_TABLE_NAME='users' THEN uid=r->>'id';
 ELSIF TG_TABLE_NAME IN ('staff_grants','diagnostic_center_assignments') THEN uid=r->>'userId';
 ELSIF TG_TABLE_NAME='sessions' THEN sid=r->>'id'; END IF;
 UPDATE diagnostic_continuity_proofs p SET "invalidatedAt"=CURRENT_TIMESTAMP
 WHERE p."invalidatedAt" IS NULL AND p."consumedReportId" IS NULL AND
  (p."candidateOrderId"=oid OR p."predecessorOrderId"=oid OR p."issuerId"=uid OR p."linkingTechnicianId"=uid OR p."issuerSessionId"=sid);
 -- No proof has a retention exception from its bound material's erasure fence.
 IF TG_TABLE_NAME IN ('diagnostic_identity_records','diagnostic_identity_evidence','diagnostic_identity_provenance')
  AND ((r->>'erasedAt') IS NOT NULL OR (r->>'cleanupRequestedAt') IS NOT NULL) THEN
  DELETE FROM diagnostic_continuity_proofs p WHERE p."candidateOrderId"=oid OR p."predecessorOrderId"=oid;
 END IF;
 RETURN NULL;
END $$;

-- Unchanged except for the private branch. A private reinspection INSERT must
-- name the proof this report has just consumed in the same transaction, by its
-- linking technician, at the proof's exact order version. The temporary public
-- equal-VIN admission stays as before. Continuity is still checked at INSERT only.
CREATE OR REPLACE FUNCTION diagnostic_report_pinned() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM inspection_orders o WHERE o.id=NEW."orderId" AND o."templateVersionId"=NEW."templateVersionId" AND o.audience=NEW.audience AND o."erasedAt" IS NULL) THEN RAISE EXCEPTION 'diagnostic_report_pinned'; END IF;
 IF TG_OP='UPDATE' THEN
  IF ROW(NEW.id,NEW."orderId",NEW."templateVersionId",NEW.audience,NEW."predecessorId",NEW.reinspection,NEW."continuityProofId",NEW."reinspectionOrderVersion") IS DISTINCT FROM ROW(OLD.id,OLD."orderId",OLD."templateVersionId",OLD.audience,OLD."predecessorId",OLD.reinspection,OLD."continuityProofId",OLD."reinspectionOrderVersion") THEN RAISE EXCEPTION 'diagnostic_report_identity_immutable'; END IF;
  IF OLD.snapshot IS NOT NULL AND ROW(NEW.snapshot,NEW."snapshotHash",NEW."finalizedAt",NEW.state->'findings',NEW.state->'observedAt',NEW.state->'mileageKm') IS DISTINCT FROM ROW(OLD.snapshot,OLD."snapshotHash",OLD."finalizedAt",OLD.state->'findings',OLD.state->'observedAt',OLD.state->'mileageKm') THEN RAISE EXCEPTION 'diagnostic_snapshot_immutable'; END IF;
  IF OLD.status IN ('finalized','withdrawn') AND NEW.status NOT IN ('finalized','withdrawn') THEN RAISE EXCEPTION 'diagnostic_snapshot_immutable'; END IF;
 END IF;
 IF NEW.reinspection THEN
  IF TG_OP='INSERT' AND NEW."continuityProofId" IS NOT NULL THEN
   IF NOT EXISTS (
    SELECT 1 FROM diagnostic_continuity_proofs c
    JOIN diagnostic_reports p ON p.id=c."predecessorReportId"
    WHERE c.id=NEW."continuityProofId" AND c."consumedReportId"=NEW.id AND c."invalidatedAt" IS NULL AND c."erasedAt" IS NULL
     AND c."candidateOrderId"=NEW."orderId" AND p.id=NEW."predecessorId" AND p.audience=NEW.audience AND p.snapshot IS NOT NULL
     AND NEW.state->>'authorId'=c."linkingTechnicianId"
     AND NEW."reinspectionOrderVersion"=(c.content->'candidate'->>'orderVersion')::int
     AND diagnostic_continuity_proof_bound(c)
   ) THEN RAISE EXCEPTION 'diagnostic_reinspection_continuity'; END IF;
  ELSIF TG_OP='INSERT' AND NOT EXISTS (
   SELECT 1 FROM diagnostic_reports p
   JOIN inspection_orders po ON po.id=p."orderId"
   JOIN inspection_orders o ON o.id=NEW."orderId"
   WHERE p.id=NEW."predecessorId" AND p."orderId"<>NEW."orderId" AND p.audience=NEW.audience AND p.snapshot IS NOT NULL AND p."erasedAt" IS NULL
    AND po."erasedAt" IS NULL AND po.audience='listing_public' AND o.audience='listing_public'
    AND o."listingId" IS NOT NULL AND o."listingId"=po."listingId"
    AND o."commissionerId" IS NOT NULL AND o."commissionerId"=po."commissionerId"
    AND o."publicationAuthorization" IS NOT NULL AND o."associationValidatedAt" IS NOT NULL
    AND o."observedVehicle"->>'method'='vin' AND po."observedVehicle"->>'method'='vin'
    AND upper(btrim(o."observedVehicle"->>'vin'))=upper(btrim(po."observedVehicle"->>'vin'))
  ) THEN RAISE EXCEPTION 'diagnostic_reinspection_continuity'; END IF;
 ELSIF NEW."predecessorId" IS NOT NULL AND NOT EXISTS (SELECT 1 FROM diagnostic_reports p WHERE p.id=NEW."predecessorId" AND p."orderId"=NEW."orderId" AND p.audience=NEW.audience AND p.snapshot IS NOT NULL) THEN RAISE EXCEPTION 'diagnostic_correction_audience';
 END IF;
 RETURN NEW;
END $$;
